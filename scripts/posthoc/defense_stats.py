#!/usr/bin/env python3
"""Statistics requested at the mock defense (post-hoc, descriptive, outside the Holm family).

Reads only locked/committed result files; reads no raw data and writes only results/posthoc/.

  1. correlation of the per-presentation difference between the two 2014 presentations of a course
     (the six courses with two presentations), per hypothesis;
  2. course-level exact sign-flip p (two-sided and one-sided) and the smallest p a design on seven
     units can reach, with and without the Holm factor 4;
  3. Bonferroni-level (98.75%) cluster bootstrap-t intervals of the four verdict pairs, same B and seed;
  4. the threshold δ as a share of the reference levels (preliminary check, development, confirmation,
     and AUC of M0 for δ_AUC);
  5. a 95% chi-square interval for each development σ (df = 8) and MDE80 at its two ends;
  6. coverage of the bootstrap-t, percentile and t intervals with n = 13 under skewed distributions.

Usage:  python3 scripts/posthoc/defense_stats.py [--fast]
"""
import argparse
import itertools
import json
import os
import sys

import numpy as np
import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, ROOT)
from src.ml import stats  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--fast", action="store_true", help="fewer simulations (smoke test)")
args = ap.parse_args()
OUT = os.path.join(ROOT, "results", "posthoc")
os.makedirs(OUT, exist_ok=True)
HYP = ["H1", "H2-a", "H3", "H4-a"]

pp = pd.read_csv(os.path.join(ROOT, "results", "conf2014", "per_presentation.csv"))
pp["course"] = pp["presentation"].str[:3]
res = {"source": "results/conf2014/per_presentation.csv (locked), results/dev2013/mde80.json, "
                 "results/dev2013/summary.md, results/conf2014/summary.md, results/conf2014/h4a_auc.csv",
       "label": "post-hoc, descriptive, outside the Holm family"}

# 1. within-course correlation (courses with a B and a J presentation)
pairs = pp.groupby("course").filter(lambda g: len(g) == 2).sort_values("presentation")
corr = {}
for h in HYP:
    b = pairs[pairs.presentation.str.endswith("B")].set_index("course")[h]
    j = pairs[pairs.presentation.str.endswith("J")].set_index("course")[h]
    corr[h] = round(float(np.corrcoef(b.loc[j.index], j)[0, 1]), 2)
res["within_course_corr"] = {"n_courses": int(pairs.course.nunique()), **corr}

# 2. course level
cl = pp.groupby("course")[HYP].mean()
signs = np.array(list(itertools.product((1.0, -1.0), repeat=len(cl))))
course = {}
for h in HYP:
    d = cl[h].to_numpy()
    stat = signs @ d / len(d)
    course[h] = {"mean": round(float(d.mean()), 4),
                 "p_two_sided": round(float((np.abs(stat) >= abs(d.mean()) - 1e-12).mean()), 4),
                 "p_one_sided": round(float((stat >= d.mean() - 1e-12).mean()), 4)}
k = len(cl)
res["course_level"] = {"n_courses": k, "min_p_two_sided": 2 / 2 ** k, "min_p_two_sided_x4": 4 * 2 / 2 ** k,
                       "min_p_one_sided": 1 / 2 ** k, "min_p_one_sided_x4": 4 / 2 ** k, **course}

# 3. Bonferroni-level intervals (same method, B and seed as the verdicts)
bonf = {}
for h in HYP:
    r = stats.cluster_bootstrap_t(pp[h].to_numpy(), n_boot=10_000, seed=0, alpha=0.05 / 4)
    bonf[h] = {"lo": round(r["lo"], 4), "hi": round(r["hi"], 4)}
res["bonferroni_98_75"] = bonf

# 4. δ as a share of the reference levels
auc = pd.read_csv(os.path.join(ROOT, "results", "conf2014", "h4a_auc.csv"))
m0 = float(auc[(auc.model == "M0") & (auc.cut == 56)].groupby("presentation").ROC_AUC.mean().mean())
levels = {"recent_pop_preliminary_FFF_2013J": 0.417,   # table 3-5 (generated by eda.py)
          "recent_pop_dev2013": 0.5412,                # results/dev2013/summary.md, task A
          "recent_pop_conf2014": 0.5698,               # results/conf2014/summary.md, task A
          "auc_M0_conf2014": round(m0, 4)}
res["delta_share"] = {k2: {"level": v, "share_pct": round(100 * 0.02 / v, 1)} for k2, v in levels.items()}

# 5. σ interval (df = 8) and MDE80 at its ends
mde = json.load(open(os.path.join(ROOT, "results", "dev2013", "mde80.json")))
rng = np.random.default_rng(0)
chi = rng.chisquare(8, 2_000_000 if args.fast else 20_000_000)
q_lo, q_hi = np.quantile(chi, [0.025, 0.975])
n_sim = 200 if args.fast else 600


def mde_scan(sigma):
    for mu in np.arange(0.02, 0.02 + 6 * sigma + 0.05, 0.0025):
        if stats.confirmation_power(float(mu), sigma, n=13, n_sim=n_sim, n_boot=2000) >= 0.8:
            return round(float(mu), 4)
    return float("nan")


sig = {}
for r in mde:
    h = r["hypothesis"]
    s = float(r["sigma_dev"])
    lo_s, hi_s = s * np.sqrt(8 / q_hi), s * np.sqrt(8 / q_lo)
    sig[h] = {"sigma_dev": round(s, 4), "sigma_ci95": [round(lo_s, 4), round(hi_s, 4)],
              "mde80_frozen": round(float(r["MDE80"]), 4), "mde80_at_ci": [mde_scan(lo_s), mde_scan(hi_s)]}
conf_sd = {h: round(float(pp[h].std(ddof=1)), 4) for h in HYP}
res["sigma"] = {"chi2_df8_quantiles": [round(float(q_lo), 3), round(float(q_hi), 3)],
                "n_sim_power": n_sim, "per_hypothesis": sig, "sigma_conf2014": conf_sd}

# 6. coverage under skew (true mean known), n = 13
n_rep = 300 if args.fast else 2000
dists = {
    "normal": lambda g, n: g.normal(0.0, 1.0, n),
    "lognormal_s0.75": lambda g, n: g.lognormal(0.0, 0.75, n) - np.exp(0.75 ** 2 / 2),
    "gamma_k2": lambda g, n: g.gamma(2.0, 1.0, n) - 2.0,
    "contaminated_10pct_x4": lambda g, n: np.where(g.random(n) < 0.1, 4.0, 1.0) * g.normal(0, 1, n),
}
cov = {}
g = np.random.default_rng(1)
for name, f in dists.items():
    hit = {"bootstrap_t": 0, "percentile": 0, "t": 0}
    for i in range(n_rep):
        d = f(g, 13)
        r = stats.cluster_bootstrap_t(d, n_boot=2000, seed=i)
        hit["bootstrap_t"] += r["lo"] <= 0 <= r["hi"]
        _, plo, phi = stats.cluster_bootstrap_ci(d, n_boot=2000, seed=i)
        hit["percentile"] += plo <= 0 <= phi
        tlo, thi = stats.t_interval(d)
        hit["t"] += tlo <= 0 <= thi
    cov[name] = {k2: round(v / n_rep, 3) for k2, v in hit.items()}
res["coverage_n13"] = {"n_rep": n_rep, "n_boot": 2000, "nominal": 0.95, **cov}

json.dump(res, open(os.path.join(OUT, "defense_stats.json"), "w"), ensure_ascii=False, indent=1)
print(json.dumps(res, ensure_ascii=False, indent=1))
