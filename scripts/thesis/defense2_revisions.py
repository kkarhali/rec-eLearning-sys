def pattern(old):
    return re.compile(DIAC.join(re.escape(c) for c in old))


def main(check=False):
    errors = 0
    changed = set()
    for e in EDITS:
        f, old, new, item = e[:4]
        count = e[4] if len(e) > 4 else 1
        p = os.path.join(ROOT, f)
        s = open(p, encoding="utf-8").read()
        rx = pattern(old)
        if s.count(new) >= count:
            continue                       # already applied
        n = len(rx.findall(s))
        if n != count:
            print(f"FAIL [{item}] {f}: found {n}, expected {count}: {old[:70]}")
            errors += 1
            continue
        if not check:
            s = rx.sub(lambda m: new, s)
            open(p, "w", encoding="utf-8").write(s)
            changed.add(f)
        print(f"ok   [{item}] {f}")
    print(f"errors={errors} files_changed={len(changed)}")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
