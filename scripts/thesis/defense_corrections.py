def main(check: bool = False) -> int:
    refs = open(os.path.join(ROOT, TH, "references.md"), encoding="utf-8").read()
    if "Next basket recommendation reality check".lower() in refs.lower():
        # renumber.py has run after these edits: citation numbers in them changed, so re-running would duplicate
        print("already applied and renumbered; nothing to do")
        return 0
    done = skipped = 0
    errors = []
    cache = {}
    for f, old, new, item in EDITS:
        p = os.path.join(ROOT, f)
        s = cache.setdefault(p, open(p, encoding="utf-8").read())
        # applied already: an extension (old ⊂ new) whose new text is present, or any edit whose old text is gone
        if (old in new and new in s) or (old not in new and old not in s and new in s):
            skipped += 1
            continue
        n = s.count(old)
        if n != 1 and not (old == H1_OLD and n >= 1):
            errors.append(f"{item} {f}: old occurs {n} times: {old[:60]}")
            continue
        cache[p] = s.replace(old, new)
        done += 1
    if errors:
        print("\n".join(errors))
        return 1
    if not check:
        for p, s in cache.items():
            open(p, "w", encoding="utf-8").write(s)
    print(f"applied={done} already={skipped} files={len(cache)}{' (check only)' if check else ''}")
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
